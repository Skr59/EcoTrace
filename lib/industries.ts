/**
 * Catalogue of pollution-creating industries and their carbon-credit position.
 *
 * For every industry we track four numbers:
 *
 *   1. liabilityT   - share of the *measured* carbon load at the reference
 *                     station that the sector is responsible for.
 *   2. requiredT    - the mandatory part of that liability (sectors covered by
 *                     India's Carbon Credit Trading Scheme / CAQM obligations).
 *   3. shouldT      - what the sector could deliver right now by deploying the
 *                     abatement technology that already exists for it.
 *   4. actualT      - the credits that have actually been issued and retired
 *                     for that sector to date.
 *
 * The gap between (3) and (4) is the real-time shortfall: pollution is being
 * produced every hour while essentially no credits are being generated for it.
 */

export type SectorKey =
  | "power"
  | "metals"
  | "minerals"
  | "chemicals"
  | "manufacturing"
  | "transport"
  | "waste"
  | "fugitive";

export interface Industry {
  key: string;
  label: string;
  sector: SectorKey;
  sectorLabel: string;
  /** Activity unit the emission factor refers to. */
  unit: string;
  /** tCO2e emitted per activity unit. */
  emissionFactor: number;
  /** Indicative annual throughput of a representative unit in the NCR cluster. */
  typicalAnnualActivity: number;
  /** Share of the measured local carbon load (%) - normalised at runtime. */
  sharePct: number;
  /** Mandatory crediting obligation under CCTS / CAQM, in % of the liability. */
  offsetObligationPct: number;
  /** Abatement technology available today for this sector. */
  abatementTech: string;
  /** Emission reduction the available technology delivers, in %. */
  abatementReductionPct: number;
  /** State of the carbon-credit registry for this sector today. */
  registryStatus: string;
  /** Credits actually issued and retired to date (tCO2e). */
  actualCreditsT: number;
  /** Dominant pollutants emitted. */
  pollutants: string[];
  note: string;
}

