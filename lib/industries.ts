export interface LedgerRow extends Industry {
  /** Normalised share of the measured local carbon load. */
  normalisedSharePct: number;
  /** tCO2e/yr of liability attributed to this sector at the station. */
  liabilityT: number;
  /** tCO2e/yr that is mandatory under the current crediting scheme. */
  requiredT: number;
  /** tCO2e/yr the sector could deliver now with existing abatement technology. */
  shouldT: number;
  /** tCO2e actually issued and retired to date. */
  actualT: number;
  /** shouldT - actualT : the real-time production shortfall. */
  deficitT: number;
  /** Share of the deliverable amount that has actually been produced, in %. */
  compliancePct: number;
  /** Monetary value of the shortfall at the current credit price. */
  deficitValueINR: number;
  /** CO2e actually emitted by a representative unit, for scale. */
  unitEmissionsT: number;
}

export interface LedgerSummary {
  liabilityT: number;
  requiredT: number;
  shouldT: number;
  actualT: number;
  deficitT: number;
  deficitValueINR: number;
  compliancePct: number;
  creditPriceINR: number;
  /** tCO2e per day the cluster should be producing in real time. */
  shouldPerDayT: number;
  actualPerDayT: number;
  deficitPerDayT: number;
  sectorCount: number;
  zeroProductionCount: number;
}

export interface LedgerInput {
  /** Total measured carbon liability at the station, in tCO2e/yr. */
  liabilityTPerYear: number;
  creditPriceINR: number;
  /** Optional user-supplied override of the credits actually produced per industry. */
  actualOverrides?: Record<string, number>;
}

/**
 * Build the required-vs-actual credit ledger for every polluting industry.
 */
export function computeIndustryLedger(input: LedgerInput): {
  rows: LedgerRow[];
  summary: LedgerSummary;
} {
  const rawTotal = INDUSTRIES.reduce((a, i) => a + i.sharePct, 0) || 1;
  const overrides = input.actualOverrides ?? {};

  const rows: LedgerRow[] = INDUSTRIES.map((ind) => {
    const normalisedSharePct = (ind.sharePct / rawTotal) * 100;
    const liabilityT = (input.liabilityTPerYear * normalisedSharePct) / 100;
    const requiredT = (liabilityT * ind.offsetObligationPct) / 100;
    const shouldT = (liabilityT * ind.abatementReductionPct) / 100;
    const actualT = overrides[ind.key] ?? ind.actualCreditsT;
    const deficitT = Math.max(0, shouldT - actualT);
    const unitEmissionsT = ind.emissionFactor * ind.typicalAnnualActivity;

    return {
      ...ind,
      normalisedSharePct,
      liabilityT,
      requiredT,
      shouldT,
      actualT,
      deficitT,
      compliancePct: shouldT > 0 ? Math.min(100, (actualT / shouldT) * 100) : 100,
      deficitValueINR: deficitT * input.creditPriceINR,
      unitEmissionsT,
    };
  });

  rows.sort((a, b) => b.deficitT - a.deficitT);

  const liabilityT = rows.reduce((a, r) => a + r.liabilityT, 0);
  const requiredT = rows.reduce((a, r) => a + r.requiredT, 0);
  const shouldT = rows.reduce((a, r) => a + r.shouldT, 0);
  const actualT = rows.reduce((a, r) => a + r.actualT, 0);
  const deficitT = rows.reduce((a, r) => a + r.deficitT, 0);

  return {
    rows,
    summary: {
      liabilityT,
      requiredT,
      shouldT,
      actualT,
      deficitT,
      deficitValueINR: deficitT * input.creditPriceINR,
      compliancePct: shouldT > 0 ? Math.min(100, (actualT / shouldT) * 100) : 0,
      creditPriceINR: input.creditPriceINR,
      shouldPerDayT: shouldT / 365,
      actualPerDayT: actualT / 365,
      deficitPerDayT: deficitT / 365,
      sectorCount: rows.length,
      zeroProductionCount: rows.filter((r) => r.actualT <= 0).length,
    },
  };
}

